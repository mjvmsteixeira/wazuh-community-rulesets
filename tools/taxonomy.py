def slug(s):
    return re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')

def classify(repo, path):
    for rr, pr, why in EXCLUDE:
        if re.search(rr, repo) and re.search(pr, path):
            return None, None, why
    for rr, pr, area, topic in MAP:
        if re.search(rr, repo) and re.search(pr, path):
            if topic is None:
                m = re.search(r'integrations/([^/]+)', path)
                g = re.search(pr, path)
                if m:
                    topic = m.group(1)
                elif g and g.groups() and g.group(1):
                    topic = g.group(1)
                else:
                    topic = re.sub(r'\.xml$', '', os.path.basename(path))
                topic = ALIASES.get(slug(topic), slug(topic))
            return area, topic, None
    return '99-unclassified', slug(repo.split('/')[1]), None
